use crate::Error;

impl Error {
    /// Human-readable Russian diagnostics shared by the desktop, Telegram and admin CLI.
    #[must_use]
    pub fn user_message(self) -> String {
        match self {
        Error::ContextInput(message) => message.into(),
        Error::ContextBudget { required, limit } => format!("Пакету нужно {required} байт, а бюджет — {limit}. Ничего не обрезано. Увеличьте бюджет или явно уберите часть выбранных записей; ограничения сохраняются целиком."),
        Error::BindingPublicationUncertain { target, .. } => format!("Сохранность привязки после сбоя диска не подтверждена: реестр мог быть уже обновлён. Проверьте память в целевом каталоге {} перед повтором; прежний путь мог быть отключён. При восстановлении используйте резервную копию всего каталога памяти.", target.display()),
        Error::BindingChanged => "Привязка памяти изменена или прежний каталог отключён. Выберите актуальный каталог и начните новую сессию.".into(),
        Error::BindingOccupied => "У целевого каталога уже есть память или привязка. Для объединения используйте экспорт/импорт; данные не заменены.".into(),
        Error::RevisionUnavailable{key,revision,available,pruned} => format!("У записи «{key}» недоступна ревизия {revision}. Доступны: {available:?}. История сокращена: {pruned}."),
        Error::Recreated => "Хранилище пересоздано. Запустите новую сессию.".into(),
        Error::StalePreview => "Данные изменились. Обновите предварительный просмотр.".into(),
        Error::Archived => "Запись в архиве. Сначала верните её в активные.".into(),
        Error::Deleted => "Ключ удалён. Восстановление возможно импортом под новым ключом.".into(),
        Error::NotFound { key, .. } => format!("Запись «{key}» не найдена в памяти выбранного проекта. Проверьте ключ и каталог проекта."),
        Error::Busy => "Хранилище памяти занято. Повторите попытку позже.".into(),
        Error::Corrupt(_) => "Файл памяти повреждён или имеет неверную структуру. Данные не изменены; проверьте резервную копию.".into(),
        Error::UnsupportedVersion(version) => format!("Формат памяти версии {version} не поддерживается этой сборкой приложения."),
        Error::ProjectMismatch => "Хранилище принадлежит другому проекту. Проверьте выбранный каталог.".into(),
        Error::UnsafePath(path) => format!("Небезопасный путь хранилища: {}. Проверьте ссылки и тип файла.", path.display()),
        Error::Io(error) => match error.kind() {
            std::io::ErrorKind::NotFound => "Файл или каталог памяти не найден. Проверьте путь и доступность диска.".into(),
            std::io::ErrorKind::PermissionDenied => "Нет доступа к файлу или каталогу памяти. Проверьте права доступа.".into(),
            std::io::ErrorKind::AlreadyExists => "Файл уже существует. Выберите другое имя, чтобы не перезаписать данные.".into(),
            _ => format!("Не удалось выполнить операцию с файлами памяти. Проверьте доступность диска, свободное место и права доступа. Код ошибки: {}.", error.raw_os_error().map_or_else(|| "не указан".into(), |code| code.to_string())),
        },
        Error::LimitExceeded(limit) => limit_message(limit).into(),
        Error::InvalidInput(reason) => input_message(reason).into(),
        Error::Conflict { expected, actual, .. } => format!("Запись обновилась: ожидалась ревизия {expected}, текущая — {actual}. Обновите данные."),
    }
    }
}

fn input_message(reason: &str) -> &str {
    match reason {
        "choose two different project directories" => {
            "Источник и целевой каталог совпадают. Выберите другой каталог; переносить память внутри одного каталога не нужно."
        }
        "source memory does not exist" | "source memory has no saved snapshot" => {
            "В исходном каталоге пока нет сохранённой памяти. Выберите проект с записями. Если проект уже перемещён, укажите его прежний полный путь."
        }
        "source must be a directory" => {
            "В качестве источника выбран файл. Укажите папку проекта, память которого нужно подключить."
        }
        "target must be a directory" => {
            "В качестве целевого каталога выбран файл. Выберите папку проекта, к которому нужно подключить память."
        }
        "source directory does not exist" => {
            "Исходный каталог не найден. Проверьте путь. Если проект уже перемещён, выберите «Перенести привязку» вместо «Подключить общую память»."
        }
        "target directory does not exist" => {
            "Целевой каталог не найден. Сначала создайте папку проекта или выберите существующую."
        }
        "project binding requires a canonical absolute UTF-8 path" => {
            "Укажите полный путь к папке проекта, без «..» и сокращения «~». После перемещения нужен прежний полный путь."
        }
        "project path must be valid UTF-8" => {
            "Не удалось прочитать символы в пути проекта. Выберите папку с именем в кодировке UTF-8."
        }
        "project must be an existing directory" => {
            "Выберите существующую папку проекта, а не файл."
        }
        "invalid memory directory" => {
            "Не удалось определить каталог памяти. Проверьте путь к хранилищу."
        }
        "project has no memory to export" => {
            "В этом проекте ещё нет памяти для экспорта. Сначала сохраните хотя бы одну запись."
        }
        "stored revisions start at 1" => {
            "Номера сохранённых версий начинаются с 1. Чтобы открыть последнюю версию, не указывайте номер или введите 0 в GUI."
        }
        "query exceeds 512 UTF-8 bytes" => {
            "Поисковый запрос слишком длинный. Сократите его до 512 байт в кодировке UTF-8."
        }
        "search limit must be between 1 and 20" => {
            "За один запрос можно получить от 1 до 20 записей. Измените количество результатов."
        }
        "query must be <=512 bytes and limit 1..20" => {
            "Сократите поисковый запрос до 512 байт и выберите от 1 до 20 результатов."
        }
        "select existing historical revisions, never the latest" => {
            "Для удаления выберите существующие старые версии. Последнюю версию записи удалить таким способом нельзя."
        }
        "key must contain 1..64 ASCII letters, digits, '_' or '-'" => {
            "Ключ записи должен содержать от 1 до 64 символов: латинские буквы, цифры, дефис или подчёркивание."
        }
        "actor must contain 1..128 UTF-8 bytes" => {
            "Укажите непустое имя автора длиной до 128 байт в кодировке UTF-8."
        }
        "title exceeds 256 or body exceeds 16384 UTF-8 bytes" => {
            "Запись слишком длинная. Сократите заголовок до 256 байт, а текст до 16384 байт в кодировке UTF-8."
        }
        "provide 1..8 nonempty sources of at most 2048 UTF-8 bytes each" => {
            "Укажите от 1 до 8 непустых источников. Каждый источник должен занимать не больше 2048 байт в кодировке UTF-8."
        }
        "copy target must be a unique unused key for a live record" | "duplicate import target" => {
            "Для импортируемой копии укажите новый, свободный ключ. Разным копиям нужны разные ключи."
        }
        "import choice refers to unknown key" | "key is absent from import preview" => {
            "Записи нет в текущем предварительном просмотре импорта. Откройте файл импорта заново и повторите выбор."
        }
        "select existing unique keys" => {
            "Выберите существующие записи без повторов. Обновите список перед подтверждением."
        }
        _ => {
            "Не удалось выполнить операцию: неверные параметры. Проверьте выбранный проект и введённые значения, затем повторите попытку."
        }
    }
}

fn limit_message(limit: &str) -> &str {
    match limit {
        "32 revisions per key" => {
            "У записи уже 32 версии. Сохраните экспорт и удалите ненужные старые версии либо явно включите автоочистку."
        }
        "500 keys per project" => {
            "В памяти уже 500 записей. Сохраните экспорт и удалите ненужные записи; архивирование не освобождает место для новых ключей."
        }
        "8 MiB per project"
        | "8 MiB per project; latest revisions cannot be removed automatically" => {
            "Память проекта достигла предела 8 МиБ. Сохраните экспорт, затем удалите ненужные записи или старые версии. Последние версии автоматически не удаляются."
        }
        "8 MiB per project; import does not auto-prune" => {
            "После импорта память превысит 8 МиБ. Сначала освободите место: импорт не удаляет старые данные автоматически."
        }
        "16 MiB import" => "Файл импорта больше 16 МиБ. Выберите файл меньшего размера.",
        "1 MiB project registry" => {
            "Список привязок проектов достиг предела 1 МиБ. Новая привязка не сохранена; сохраните резервную копию каталога памяти перед обслуживанием реестра."
        }
        "4096 tombstones" => {
            "Накопилось 4096 отметок об удалённых записях. Сохраните экспорт и используйте «Новое поколение», выбрав нужные записи."
        }
        "revision range" => {
            "Достигнут предел номера версии записи. Сохраните экспорт и перенесите нужное содержимое под новым ключом."
        }
        "generation range" | "snapshot generation range" => {
            "Достигнут предел счётчика изменений памяти. Сохраните экспорт и восстановите его в новом изолированном проекте."
        }
        _ => {
            "Достигнут лимит хранилища памяти. Проверьте его состояние и сохраните экспорт перед очисткой."
        }
    }
}
